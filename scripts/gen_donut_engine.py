#!/usr/bin/env python3
"""Generate examples/donut_engine.si: a live polygonal torus streaming to the
SDL2 host in host/donut_host.c.

sigi's while form peeks the stack top before each iteration, so loops follow
one discipline: the body drops the incoming condition with `$` first and
pushes the next condition as its final act. The frame loop never ends on its
own; run the program through the host (or Ctrl-C) to stop.
"""

import math
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent

R, TUBE = 3.0, 1.25
RING, TUBE_N = 16, 10
SCALE, OX, OY = 28.0, 120.0, 120.0
SPIN_STEP = 0.05
TILT = 0.72
LIGHT = (0.32, 0.58, 0.75)
TH_STEP = 2 * math.pi / RING
PH_STEP = 2 * math.pi / TUBE_N
CB, SB = round(math.cos(TILT), 12), round(math.sin(TILT), 12)
NL = r"!10 ^"

# Slots: 1 A, 2 ca, 3 sa, 4 i, 5 j, 6..9 ct1 st1 ct2 st2,
# 10..13 cp1 sp1 cp2 sp2, 14 rad, 15 x, 16 y, 17 z, 18 cy, 19 cz,
# 20 nx, 21 ny, 22 nz, 23 lum, 24 cr, 25 cg, 26 cb-col
P = []


def put(*ops):
    P.append(" ".join(str(o) for o in ops))


def num(v):
    return "!{}".format(repr(round(v, 12)))


ld = lambda n: "<{}>".format(n)
st = lambda n: "!{} :".format(n)


def comment(text):
    P.append("\\ " + text)


def emit_str(s):
    put('"{}"'.format(s), NL)


def corner(cp, sp, ct, st_):
    put(ld(cp), num(TUBE), "*", num(R), "+", st(14))
    put(ld(14), ld(ct), "*", st(15))
    put(ld(sp), num(TUBE), "*", st(16))
    put(ld(14), ld(st_), "*", st(17))
    put(ld(16), ld(2), "*", ld(17), ld(3), "*", "-", st(18))
    put(ld(16), ld(3), "*", ld(17), ld(2), "*", "+", st(19))
    # px = OX + (x*cb + cz*sb)*SCALE ; py = OY - cy*SCALE
    put(
        ld(15),
        num(CB),
        "*",
        ld(19),
        num(SB),
        "*",
        "+",
        num(SCALE),
        "*",
        num(OX),
        "+",
        "|",
    )
    put(num(OY), ld(18), num(SCALE), "*", "-", "|")


comment("A live spinning torus, streaming shaded quads for donut_host (SDL2).")
comment("Generated by scripts/gen_donut_engine.py; run:")
comment("  ./build/sigic examples/donut_engine.si --run --cc cc | ./host/donut_host")
put(num(0.0), st(1))  # A = 0

put("!1")  # seed frame-loop condition
P.append("[")
put("$")  # drop incoming condition
put(ld(1), num(SPIN_STEP), "+", st(1))
put(ld(1), "C", st(2))  # ca = cos A
put(ld(1), "S", st(3))  # sa = sin A
emit_str("F")
put(num(0.0), st(4))  # i = 0

put("!1")  # seed ring-loop condition
P.append("[")
put("$")
for idx, (ct, stt) in enumerate(((6, 7), (8, 9))):
    if idx == 0:
        put(ld(4), "C", st(6))
        put(ld(4), "S", st(7))
    else:
        put(ld(4), num(TH_STEP), "+", "C", st(8))
        put(ld(4), num(TH_STEP), "+", "S", st(9))

put(num(0.0), st(5))  # j = 0
put("!1")  # seed tube-loop condition
P.append("[")
put("$")

put(ld(5), "C", st(10))
put(ld(5), "S", st(11))
put(ld(5), num(PH_STEP), "+", "C", st(12))
put(ld(5), num(PH_STEP), "+", "S", st(13))

# Rotated normal at (phi, theta), light, colour band.
put(ld(11), ld(2), "*", ld(10), ld(7), "*", ld(3), "*", "-", st(21))
put(ld(11), ld(3), "*", ld(10), ld(7), "*", ld(2), "*", "+", st(22))
put(ld(10), ld(6), "*", num(CB), "*", ld(22), num(SB), "*", "+", st(20))
put(
    ld(20),
    num(LIGHT[0]),
    "*",
    ld(21),
    num(LIGHT[1]),
    "*",
    "+",
    ld(22),
    num(LIGHT[2]),
    "*",
    "+",
    num(1.0),
    "+",
    num(0.5),
    "*",
    st(23),
)
put(ld(23), num(150.0), "*", num(80.0), "+", st(24))
put(ld(23), num(90.0), "*", num(50.0), "+", st(25))
put(ld(23), num(60.0), "*", num(30.0), "+", st(26))

emit_str("P")
for cp, sp, ct, stt in ((10, 11, 6, 7), (12, 11, 6, 7), (12, 11, 8, 9), (10, 11, 8, 9)):
    corner(cp, sp, ct, stt)
put(ld(24), "|")
put(ld(25), "|")
put(ld(26), "|")

put(ld(5), num(PH_STEP), "+", st(5))
put(ld(5), num(TUBE_N), "<")  # tube condition
P.append("]")
put("$")
put(ld(4), num(TH_STEP), "+", st(4))
put(ld(4), num(RING), "<")  # ring condition
P.append("]")
put("$")
emit_str("S")
put("!1")  # frame condition: forever
P.append("]")

text = "\n".join(P) + "\n"
(ROOT / "examples" / "donut_engine.si").write_text(text, encoding="utf-8")
print("wrote examples/donut_engine.si: {} lines".format(len(text.splitlines())))
